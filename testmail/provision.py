#!/usr/bin/env python3
"""Configure a fresh Stalwart data store for local testing.

Called by scripts/testmail.sh in two phases. Phase "recovery" runs while
Stalwart is in recovery mode and talks to the management API (JMAP,
`urn:stalwart:jmap`) as the one-time recovery administrator whose password is
passed in TESTMAIL_PROVISION_PASSWORD. Phase "defaults" runs after the first
normal start (which creates default MTA objects) as admin@vicemail.test.

Everything the server would otherwise fetch from the internet (web UI, spam
rules, ASN/GeoIP data) is switched off, outbound delivery is impossible, and
all listeners bind to 127.0.0.1 only.
"""

from __future__ import annotations

import argparse
import base64
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path

sys.dont_write_bytecode = True  # keep testmail/ free of __pycache__
sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import load_env  # noqa: E402

USING = ["urn:ietf:params:jmap:core", "urn:stalwart:jmap"]


class ProvisionError(Exception):
    pass


class Jmap:
    def __init__(self, url: str, user: str, password: str) -> None:
        self.url = url.rstrip("/") + "/jmap/"
        token = base64.b64encode(f"{user}:{password}".encode()).decode()
        self.headers = {"Authorization": f"Basic {token}", "Content-Type": "application/json"}

    def call(self, *calls: list) -> list:
        body = json.dumps({"using": USING, "methodCalls": list(calls)}).encode()
        req = urllib.request.Request(self.url, data=body, headers=self.headers)
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                data = json.load(resp)
        except urllib.error.HTTPError as err:
            raise ProvisionError(f"HTTP {err.code}: {err.read().decode(errors='replace')}") from err
        responses = data.get("methodResponses", [])
        for name, args, call_id in responses:
            if name == "error":
                raise ProvisionError(f"{call_id}: {args}")
            for key in ("notCreated", "notUpdated", "notDestroyed"):
                if args.get(key):
                    raise ProvisionError(f"{call_id} {name} {key}: {json.dumps(args[key])}")
        return responses

    def create(self, obj: str, items: dict[str, dict]) -> dict[str, str]:
        [(_, args, _)] = self.call([f"x:{obj}/set", {"create": items}, obj])
        created = args.get("created", {})
        missing = set(items) - set(created)
        if missing:
            raise ProvisionError(f"{obj}: not created: {sorted(missing)}")
        return {key: value["id"] for key, value in created.items()}

    def update_singleton(self, obj: str, patch: dict) -> None:
        [(_, args, _)] = self.call([f"x:{obj}/set", {"update": {"singleton": patch}}, obj])
        if "singleton" not in args.get("updated", {}):
            raise ProvisionError(f"{obj}: singleton not updated: {args}")

    def get(self, obj: str, ids: list[str] | None) -> list[dict]:
        [(_, args, _)] = self.call([f"x:{obj}/get", {"ids": ids}, obj])
        return args["list"]


def expr(value: str, match: list[tuple[str, str]] | None = None) -> dict:
    """Stalwart expression object: optional if/then list plus else."""
    out: dict = {"else": value}
    if match is not None:
        out["match"] = {str(i): {"if": cond, "then": then} for i, (cond, then) in enumerate(match)}
    return out


def provision(api: Jmap, env: dict[str, str], tls_dir: Path) -> None:
    host = env["TESTMAIL_HOST"]
    if host != "127.0.0.1":
        raise ProvisionError("TESTMAIL_HOST must be 127.0.0.1")
    domain = env["TESTMAIL_DOMAIN"]
    smtp_plain_port = env["TESTMAIL_SMTP_PORT"]

    # TLS certificate generated by testmail.sh, stored inline so the data store
    # does not depend on the checkout path.
    cert_ids = api.create("Certificate", {
        "server": {
            "certificate": {"@type": "Text", "value": (tls_dir / "server.pem").read_text()},
            "privateKey": {"@type": "Text", "secret": (tls_dir / "server-key.pem").read_text()},
        }
    })

    domain_ids = api.create("Domain", {
        "dom": {
            "name": domain,
            "description": "Vice Mail local test domain",
            "certificateManagement": {"@type": "Manual"},
            "dkimManagement": {"@type": "Manual"},
            "dnsManagement": {"@type": "Manual"},
        }
    })
    domain_id = domain_ids["dom"]

    def user(prefix: str, description: str, admin: bool = False) -> dict:
        address = env[f"TESTMAIL_{prefix}_ADDRESS"]
        local, _, addr_domain = address.partition("@")
        if addr_domain != domain:
            raise ProvisionError(f"{address} is not in {domain}")
        body = {
            "@type": "User",
            "name": local,
            "domainId": domain_id,
            "description": description,
            "credentials": {"0": {"@type": "Password", "secret": env[f"TESTMAIL_{prefix}_PASSWORD"]}},
        }
        if admin:
            body["roles"] = {"@type": "Admin"}
        return body

    api.create("Account", {
        "alice": user("ALICE", "Alice Archer (test account)"),
        "bob": user("BOB", "Bob Baker (test account)"),
        "admin": user("ADMIN", "Administrator of the local test server", admin=True),
    })

    def bind(port_key: str) -> dict:
        return {f"{host}:{env[port_key]}": True}

    api.create("NetworkListener", {
        "imap": {"name": "imap", "protocol": "imap", "bind": bind("TESTMAIL_IMAP_PORT"),
                 "useTls": True, "implicitTls": False},
        "imaps": {"name": "imaps", "protocol": "imap", "bind": bind("TESTMAIL_IMAPS_PORT"),
                  "useTls": True, "implicitTls": True},
        "smtp": {"name": "smtp", "protocol": "smtp", "bind": bind("TESTMAIL_SMTP_PORT"),
                 "useTls": True, "implicitTls": False},
        "submission": {"name": "submission", "protocol": "smtp",
                       "bind": bind("TESTMAIL_SUBMISSION_PORT"), "useTls": True, "implicitTls": False},
        "submissions": {"name": "submissions", "protocol": "smtp",
                        "bind": bind("TESTMAIL_SMTPS_PORT"), "useTls": True, "implicitTls": True},
        "http": {"name": "http", "protocol": "http", "bind": bind("TESTMAIL_HTTP_PORT"),
                 "useTls": False, "implicitTls": False},
    })

    api.update_singleton("SystemSettings", {
        "defaultHostname": f"mail.{domain}",
        "defaultDomainId": domain_id,
        "defaultCertificateId": cert_ids["server"],
    })

    # Mailboxes every new account gets (with SPECIAL-USE attributes).
    folder = lambda name: {"name": name, "create": True, "subscribe": True}  # noqa: E731
    api.update_singleton("Email", {
        "defaultFolders": {
            "inbox": folder("INBOX"),
            "sent": folder("Sent"),
            "drafts": folder("Drafts"),
            "archive": folder("Archive"),
            "junk": folder("Junk"),
            "trash": folder("Trash"),
        }
    })

    # Tests hammer the server from one IP: no rate limits, no auto-ban.
    api.update_singleton("Imap", {"rateLimit": None})
    api.update_singleton("Http", {"rateLimitAnonymous": None, "rateLimitAuthenticated": None})
    api.update_singleton("Security", {
        "abuseBanRate": None, "authBanRate": None, "loiterBanRate": None, "scanBanRate": None,
    })

    # No internet: spam filter (rules download, DNSBL, URL checks) and ASN/GeoIP off.
    api.update_singleton("SpamSettings", {"enable": False, "spamFilterRulesUrl": None})
    api.update_singleton("Asn", {"@type": "Disabled"})
    api.update_singleton("SenderAuth", {
        "dkimVerify": expr("disable"), "arcVerify": expr("disable"),
        "dmarcVerify": expr("disable", []), "reverseIpVerify": expr("disable", []),
        "spfEhloVerify": expr("disable", []), "spfFromVerify": expr("disable", []),
    })

    # SMTP: AUTH required everywhere except the local-delivery port; nobody may
    # relay, and the only route is local delivery, so no mail leaves the machine.
    api.update_singleton("MtaStageAuth", {
        "require": expr(f"local_port != {smtp_plain_port}", []),
        "saslMechanisms": expr("false", [(f"local_port != {smtp_plain_port} && is_tls", "[plain, login]")]),
    })
    # No tarpitting (5 s by default after a failed AUTH or RCPT): tests provoke failures on purpose.
    # Not "0s": with a zero duration Stalwart 1.1.1 never answers the failed command.
    api.update_singleton("MtaStageRcpt", {"allowRelaying": expr("false", []), "waitOnFail": expr("1ms", [])})
    api.update_singleton("MtaStageAuth", {"waitOnFail": expr("1ms", [])})
    api.update_singleton("MtaOutboundStrategy", {"route": expr("'local'", [])})
    api.update_singleton("MtaStageData", {
        "enableSpamFilter": expr("false", []),
        "dkimSignDomain": expr("false", []),
        "addReceivedHeader": expr("true", []),
        "addReturnPathHeader": expr("true", []),
    })

    # IMAP SEARCH HEADER only finds headers the search index covers; by default that is just
    # From/To/Cc/Bcc/Subject. Index all headers so Message-ID, List-Id, X-Vicemail-Seed etc. work.
    api.update_singleton("Search", {"indexEmailFields/headers": True})

    # Keep seeded Trash/Junk content stable instead of auto-expunging after 30 days.
    api.update_singleton("DataRetention", {"expungeTrashAfter": None})

    # The bundled web UI would be downloaded from GitHub on demand: disable it.
    apps = api.get("Application", None)
    if apps:
        [(_, args, _)] = api.call(["x:Application/set", {
            "update": {app["id"]: {"enable": False} for app in apps}}, "apps"])
        if len(args.get("updated", {})) != len(apps):
            raise ProvisionError(f"Application not disabled: {args}")

    # Log to stdout; testmail.sh redirects it to testmail/.data/stalwart.log.
    api.create("Tracer", {"log": {"@type": "Stdout", "level": "info", "ansi": False, "buffered": False}})

    # Read back what matters.
    listeners = api.get("NetworkListener", None)
    binds = sorted(b for item in listeners for b in item["bind"])
    if any(not b.startswith(f"{host}:") for b in binds):
        raise ProvisionError(f"listener not bound to {host}: {binds}")
    accounts = sorted(a["emailAddress"] for a in api.get("Account", None))
    print(f"provisioned domain {domain}, accounts {', '.join(accounts)}")
    print(f"listeners: {', '.join(binds)}")


def adjust_defaults(api: Jmap) -> None:
    """Second phase, after the first normal start created the default MTA objects.

    The default inbound throttles (5 connections per second per IP, 25 mails per
    hour per sender domain and recipient) would make integration tests flaky.
    """
    throttles = api.get("MtaInboundThrottle", None)
    if throttles:
        [(_, args, _)] = api.call(["x:MtaInboundThrottle/set", {
            "update": {t["id"]: {"enable": False} for t in throttles}}, "throttles"])
        if len(args.get("updated", {})) != len(throttles):
            raise ProvisionError(f"MtaInboundThrottle not disabled: {args}")
    still_enabled = [t for t in api.get("MtaInboundThrottle", None) if t["enable"]]
    if still_enabled:
        raise ProvisionError(f"throttles still enabled: {still_enabled}")

    # The first normal start resets the ASN/GeoIP source to GitHub downloads; switch it off again.
    api.update_singleton("Asn", {"@type": "Disabled"})

    # Verify that the settings from the recovery phase survived the first start.
    checks = {
        "Asn": lambda o: o["@type"] == "Disabled",
        "SpamSettings": lambda o: o["enable"] is False and o["spamFilterRulesUrl"] is None,
        "Search": lambda o: o["indexEmailFields"].get("headers") is True,
        "MtaStageRcpt": lambda o: o["allowRelaying"]["else"] == "false",
        "MtaOutboundStrategy": lambda o: o["route"]["else"] == "'local'" and not o["route"]["match"],
        "Security": lambda o: o["authBanRate"] is None,
        "Imap": lambda o: o["rateLimit"] is None,
    }
    for obj, ok in checks.items():
        [value] = api.get(obj, ["singleton"])
        if not ok(value):
            raise ProvisionError(f"{obj} lost its test settings: {json.dumps(value)[:300]}")
    if any(app["enable"] for app in api.get("Application", None)):
        raise ProvisionError("web UI application is enabled again")
    print(f"disabled {len(throttles)} default SMTP inbound throttles and ASN/GeoIP downloads; settings verified")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--url", required=True, help="management URL (http://127.0.0.1:PORT)")
    parser.add_argument("--phase", choices=["recovery", "defaults"], required=True,
                        help="recovery: initial setup as the recovery administrator; "
                             "defaults: adjust objects created at the first normal start")
    parser.add_argument("--tls-dir", type=Path, help="directory with server.pem and server-key.pem")
    args = parser.parse_args()
    env = load_env()
    try:
        if args.phase == "recovery":
            password = os.environ.get("TESTMAIL_PROVISION_PASSWORD")
            if not password or not args.tls_dir:
                print("TESTMAIL_PROVISION_PASSWORD and --tls-dir are required", file=sys.stderr)
                return 2
            provision(Jmap(args.url, "provision", password), env, args.tls_dir)
        else:
            adjust_defaults(Jmap(args.url, env["TESTMAIL_ADMIN_ADDRESS"], env["TESTMAIL_ADMIN_PASSWORD"]))
    except (ProvisionError, OSError, KeyError) as err:
        print(f"provisioning failed: {err}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
