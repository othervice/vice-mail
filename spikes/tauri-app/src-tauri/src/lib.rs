//! Spike C: smallest Tauri 2 app with typed commands and a typed event stream.
//! Spike D: HTML sandbox (navigation hook, breach detector) and desktop tests (`e2e` feature).

pub mod commands;
#[cfg(feature = "e2e")]
pub mod e2e;
pub mod model;
pub mod sandbox;

use specta_typescript::Typescript;
use tauri::Manager;
use tauri_specta::{Builder, ErrorHandlingMode, collect_commands, collect_events};

/// Single source of truth for commands and events (tauri-specta).
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            commands::get_message,
            commands::start_demo_sync,
            commands::report_frontend,
            sandbox::sandbox_breach,
            sandbox::sandbox_report,
            sandbox::sandbox_reset,
        ])
        .events(collect_events![model::CoreEvent, sandbox::SandboxEvent])
        .error_handling(ErrorHandlingMode::Result)
        // IPC types are one-way (args in, results/events out); one alias per type is clearer
        // than the `_Serialize | _Deserialize` pairs specta emits by default.
        .disable_serde_phases()
        .constant("CORE_EVENT_NAME", model::CORE_EVENT_NAME)
}

/// TypeScript exporter settings shared by the app and the freshness test.
pub fn typescript() -> Typescript {
    Typescript::default().header("// Generated by tauri-specta from src-tauri. Do not edit.\n")
}

pub fn run() {
    let builder = specta_builder();
    let specta_handler = builder.invoke_handler();
    #[cfg(feature = "e2e")]
    let e2e_handler: Box<dyn Fn(tauri::ipc::Invoke<tauri::Wry>) -> bool + Send + Sync> =
        Box::new(tauri::generate_handler![e2e::e2e_native_mouse]);

    let app = tauri::Builder::default();
    // Test builds only: embedded W3C WebDriver server for WebdriverIO (@wdio/tauri-service).
    // It listens on 127.0.0.1:$TAURI_WEBDRIVER_PORT (default 4445). Never in a normal build.
    #[cfg(feature = "e2e")]
    let app = app.plugin(tauri_plugin_wdio_webdriver::init());

    app.manage(sandbox::SandboxState::default())
        .invoke_handler(move |invoke| {
            // Log every command that reaches the core, whatever frame or origin sent it.
            let name = invoke.message.command().to_owned();
            if let Some(state) = invoke
                .message
                .webview()
                .try_state::<sandbox::SandboxState>()
            {
                state.log_command(&name);
            }
            #[cfg(feature = "e2e")]
            if name.starts_with("e2e_") {
                return e2e_handler(invoke);
            }
            specta_handler(invoke)
        })
        .setup(move |app| {
            builder.mount_events(app);
            // The window is built in code (not in tauri.conf.json) to attach the navigation hook.
            let handle = app.handle().clone();
            tauri::WebviewWindowBuilder::new(
                app,
                "main",
                tauri::WebviewUrl::App("index.html".into()),
            )
            .title("Vice Mail Spike")
            .inner_size(900.0, 700.0)
            .on_navigation(move |url| sandbox::decide_navigation(&handle, url))
            .build()?;
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}

#[cfg(test)]
mod tests {
    use std::fs;
    use std::path::{Path, PathBuf};

    use ts_rs::TS;

    use super::*;
    use crate::model::*;

    fn manifest_dir() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR"))
    }

    fn scratch_dir(name: &str) -> PathBuf {
        let dir =
            std::env::temp_dir().join(format!("vice-mail-spike-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).expect("create scratch dir");
        dir
    }

    fn update_requested() -> bool {
        std::env::var("UPDATE_BINDINGS").as_deref() == Ok("1")
    }

    /// Fails when `src/generated/tauri-specta/bindings.ts` is stale.
    /// `UPDATE_BINDINGS=1 cargo test` rewrites it.
    #[test]
    fn tauri_specta_bindings_are_fresh() {
        let committed = manifest_dir().join("../src/generated/tauri-specta/bindings.ts");
        let fresh = scratch_dir("specta").join("bindings.ts");
        specta_builder()
            .export(typescript(), &fresh)
            .expect("tauri-specta export");
        let fresh_text = fs::read_to_string(&fresh).expect("read fresh bindings");

        if update_requested() {
            fs::create_dir_all(committed.parent().unwrap()).unwrap();
            fs::write(&committed, &fresh_text).unwrap();
            return;
        }
        let committed_text = fs::read_to_string(&committed).unwrap_or_default();
        assert!(
            committed_text == fresh_text,
            "{} is stale; run `UPDATE_BINDINGS=1 cargo test`",
            committed.display()
        );
    }

    fn ts_rs_export_into(dir: &Path) {
        let cfg = ts_rs::Config::new().with_out_dir(dir);
        MessageQuery::export_all(&cfg).expect("export MessageQuery");
        MessageDetail::export_all(&cfg).expect("export MessageDetail");
        IpcError::export_all(&cfg).expect("export IpcError");
        CoreEvent::export_all(&cfg).expect("export CoreEvent");
    }

    fn list_ts_files(dir: &Path) -> Vec<(String, String)> {
        let mut files: Vec<_> = fs::read_dir(dir)
            .map(|rd| rd.filter_map(Result::ok).collect())
            .unwrap_or_else(|_| Vec::new())
            .into_iter()
            .filter(|e| e.path().extension().is_some_and(|x| x == "ts"))
            .map(|e| {
                (
                    e.file_name().to_string_lossy().into_owned(),
                    fs::read_to_string(e.path()).unwrap(),
                )
            })
            .collect();
        files.sort();
        files
    }

    /// Fails when `src/generated/ts-rs/` is stale (changed, missing or leftover files).
    #[test]
    fn ts_rs_bindings_are_fresh() {
        let committed = manifest_dir().join("../src/generated/ts-rs");
        let fresh = scratch_dir("tsrs");
        ts_rs_export_into(&fresh);

        if update_requested() {
            let _ = fs::remove_dir_all(&committed);
            fs::create_dir_all(&committed).unwrap();
            for (name, text) in list_ts_files(&fresh) {
                fs::write(committed.join(name), text).unwrap();
            }
            return;
        }
        assert!(
            list_ts_files(&committed) == list_ts_files(&fresh),
            "{} is stale; run `UPDATE_BINDINGS=1 cargo test`",
            committed.display()
        );
    }

    #[test]
    fn error_crosses_the_bridge_as_code_message_detail() {
        let err = commands::get_message(MessageQuery {
            account_id: "acc-1".into(),
            uid: 0,
            include_body: false,
        })
        .unwrap_err();
        let json = serde_json::to_value(&err).unwrap();
        assert_eq!(json["code"], "not_found");
        assert!(json["message"].is_string());
        assert!(json["detail"].is_string());
    }

    #[test]
    fn mod_seq_is_a_string_and_sizes_are_numbers() {
        let msg = commands::get_message(MessageQuery {
            account_id: "acc-1".into(),
            uid: 42,
            include_body: true,
        })
        .unwrap();
        let json = serde_json::to_value(&msg).unwrap();
        assert_eq!(json["modSeq"], commands::DEMO_MOD_SEQ.to_string());
        assert!(json["sizeBytes"].is_u64());
        assert!(json["internalDateMs"].is_i64());
        assert_eq!(json["body"]["kind"], "html");
        assert_eq!(json["body"]["blockedRemoteImages"], 2);
        assert_eq!(json["flags"][1]["kind"], "keyword");
        assert_eq!(json["sentAt"], "2026-11-20T09:30:00Z");
    }

    #[derive(serde::Serialize, specta::Type, ts_rs::TS)]
    struct UnannotatedU64 {
        n: u64,
    }

    /// Documents the default handling of a `u64` without an explicit mapping.
    #[test]
    fn unannotated_u64_specta_refuses_ts_rs_emits_bigint() {
        let out = scratch_dir("bigint").join("bindings.ts");
        let specta = Builder::<tauri::Wry>::new()
            .typ::<UnannotatedU64>()
            .export(typescript(), &out);
        assert!(specta.is_err(), "specta-typescript must refuse a bare u64");

        let decl = UnannotatedU64::decl(&ts_rs::Config::new());
        assert!(decl.contains("n: bigint"), "ts-rs default: {decl}");
    }

    #[test]
    fn event_is_tagged_by_type() {
        let event = CoreEvent::SyncProgress {
            account_id: "acc-1".into(),
            mailbox: "INBOX".into(),
            done: 1,
            total: 5,
        };
        let json = serde_json::to_value(&event).unwrap();
        assert_eq!(json["type"], "syncProgress");
        assert_eq!(json["accountId"], "acc-1");
        assert_eq!(CORE_EVENT_NAME, "core-event");
    }
}
