# Wordmark letters: a squared geometric sans drawn after the original (cap height 100, y down,
# baseline at 100). Each function returns (path, advance width).

C, X, S, SH = 100, 80, 22, 19  # cap height, x-height, stem, horizontal stroke
R, RI = 24, 6  # outer and inner corner radius of round letters
TOP = C - X  # y of the x-height line


def letter_v():
    W, fb = 114, 9
    slope = (W / 2 - fb) / C  # dx per dy of the outer edge
    hw = S * (1 + slope ** 2) ** 0.5  # horizontal width of a diagonal stroke of width S
    notch = (W / 2 - hw) / slope
    return f"M0 0H{n(hw)}L{n(W / 2)} {n(notch)}L{n(W - hw)} 0H{W}L{n(W / 2 + fb)} {C}H{n(W / 2 - fb)}Z", W


def letter_i(x_height=X):
    gap = 9
    dot_bottom = C - x_height - gap
    return (f"M0 {C - x_height}H{S}V{C}H0Z"
            f"M0 {n(dot_bottom - S + 2)}A2 2 0 0 1 2 {n(dot_bottom - S)}H{S - 2}A2 2 0 0 1 {S} {n(dot_bottom - S + 2)}"
            f"V{n(dot_bottom)}H0Z"), S


def letter_l():
    return f"M0 0H{S}V{C}H0Z", S


def letter_c():
    W = 70
    b = C
    return (f"M{W} {TOP}H{R}A{R} {R} 0 0 0 0 {TOP + R}V{b - R}A{R} {R} 0 0 0 {R} {b}H{W}V{b - SH}"
            f"H{S + RI}A{RI} {RI} 0 0 1 {S} {b - SH - RI}V{TOP + SH + RI}A{RI} {RI} 0 0 1 {S + RI} {TOP + SH}"
            f"H{W}Z"), W


def letter_e():
    W, bar = 74, 16
    b = C
    bar_top = TOP + (X - bar) / 2 - 1
    bar_bottom = bar_top + bar
    outer = (f"M{W - R} {TOP}H{R}A{R} {R} 0 0 0 0 {TOP + R}V{b - R}A{R} {R} 0 0 0 {R} {b}H{W}V{b - SH}"
             f"H{S + RI}A{RI} {RI} 0 0 1 {S} {b - SH - RI}V{n(bar_bottom)}H{W}V{TOP + R}"
             f"A{R} {R} 0 0 0 {W - R} {TOP}Z")
    hole = (f"M{S + RI} {TOP + SH}H{W - S - RI}A{RI} {RI} 0 0 1 {W - S} {TOP + SH + RI}V{n(bar_top)}H{S}"
            f"V{TOP + SH + RI}A{RI} {RI} 0 0 1 {S + RI} {TOP + SH}Z")
    return outer + hole, W


def letter_a():
    W, ta, R2 = 68, 5, 18
    b = C
    bowl = TOP + 35  # outer top of the bowl
    sh2 = 16
    outer = (f"M{ta} {TOP}H{W - R}A{R} {R} 0 0 1 {W} {TOP + R}V{b}H{R2}A{R2} {R2} 0 0 1 0 {b - R2}"
             f"V{bowl + R2}A{R2} {R2} 0 0 1 {R2} {bowl}H{W - S}V{TOP + SH + RI}"
             f"A{RI} {RI} 0 0 0 {W - S - RI} {TOP + SH}H{ta}Z")
    hole = (f"M{S + RI} {bowl + sh2}H{W - S}V{b - SH}H{S + RI}A{RI} {RI} 0 0 1 {S} {b - SH - RI}"
            f"V{bowl + sh2 + RI}A{RI} {RI} 0 0 1 {S + RI} {bowl + sh2}Z")
    return outer + hole, W


def letter_m():
    W, d0, yv, t = 120, 3, 42, 21
    dx, dy = W / 2 - (S + d0), yv
    length = (dx * dx + dy * dy) ** 0.5
    tv = t * length / dx  # vertical thickness of the diagonal
    yi = yv - dy / dx * (W / 2 - S) + tv  # lower edge meets the inner side of the stem
    return (f"M0 {C}V0H{S + d0}L{n(W / 2)} {yv}L{W - S - d0} 0H{W}V{C}H{W - S}V{n(yi)}"
            f"L{n(W / 2)} {n(yv + tv)}L{S} {n(yi)}V{C}Z"), W


GAP, SPACE = 10, 30  # letter and word spacing


def word(letters):
    paths, x = [], 0
    for i, (d, w) in enumerate(letters):
        paths.append(f'<path transform="translate({n(x)} 0)" d="{d}" fill-rule="evenodd"/>')
        x += w + (GAP if i < len(letters) - 1 else 0)
    return "\n".join(paths), x


def wordmark(theme):
    """Mark on the left (with speed lines), then "Vice" and "Mail"."""
    vice, vice_w = word([letter_v(), letter_i(), letter_c(), letter_e()])
    mail, mail_w = word([letter_m(), letter_a(), letter_i(), letter_l()])
    k = 205 / (ENV[3] - V_TOP)  # mark height = 2.05 cap heights
    # As in the original, the speed lines run on above the start of "Vice".
    text_x = (ENV[2] - ENV[0]) * k + 34
    text_y = (ENV[3] - V_TOP) * k / 2 - C / 2
    width = text_x + vice_w + SPACE + mail_w
    height = (ENV[3] - V_TOP) * k
    vice_fill = "#ffffff" if theme == "dark" else INK
    p = "m-"
    body = "\n".join([
        f"<defs>\n{mark_defs(p)}\n"
        + grad("mail", [(0, "#4493f8"), (1, "#1f6feb")], user=(0, 0, 0, C)) + "\n</defs>",
        f'<g transform="scale({n(k)}) translate({-ENV[0]} {-V_TOP})">\n{mark(p, detail=False, speed=True)}\n</g>',
        f'<g transform="translate({n(text_x)} {n(text_y)})" fill="{vice_fill}">\n{vice}\n</g>',
        f'<g transform="translate({n(text_x + vice_w + SPACE)} {n(text_y)})" fill="url(#mail)">\n{mail}\n</g>',
    ])
    return svg((0, -0.5, width, height + 1), body, size=(round(width * 2), round((height + 1) * 2)))


def mark_only():
    p = "m-"
    x0, x1 = ENV[0], ENV[2]
    content = f"<defs>\n{mark_defs(p)}\n</defs>\n{mark(p, detail=False)}"
    return svg((x0, V_TOP, x1 - x0, ENV[3] - V_TOP), content)


