#!/usr/bin/env python3
"""Writes every Vice Mail brand SVG from one set of shapes (standard library only).

  python3 docs/brand/make_svgs.py

Outputs
  app/src-tauri/icons/source.svg            app icon master, macOS grid (824 body in 1024, shadow)
  app/src-tauri/icons/source-windows.svg    same artwork, Windows framing (body fills 88 %, no shadow)
  app/src-tauri/icons/source-{16,20,24,30,32,36,40,48}.svg
                                            simplified icon, drawn on each size's own pixel grid, Windows framing
  app/src-tauri/icons/source-macos-{16,32}.svg       simplified icon, pixel-snapped, macOS margins
  docs/brand/icon.svg, mark.svg, glyph-mono.svg, wordmark-dark.svg, wordmark-light.svg

scripts/icons.sh runs this script and then rasterises the SVGs, so a change here
reaches every icon file with one command. The letters of the wordmark are drawn here as outlines
(no font is used or embedded).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ICONS = ROOT / "app" / "src-tauri" / "icons"
BRAND = ROOT / "docs" / "brand"

# Palette (also listed in docs/brand/README.md). Blue since 25 Nov 2026 (decision 0068): the
# GitHub blues of the app's colour scheme (decision 0053) in place of the former orange.
SKY = "#a5d6ff"  # light blue: top of the V, outer edge of the rim
BLUE = "#4493f8"  # brand blue: the V, the envelope outline, "Mail"
DEEP_BLUE = "#1f6feb"  # deep blue: bottom of the V and of the outlines
NIGHT = "#0d1117"  # icon body, near-black with a cool cast (GitHub dark)
INK = "#1f2328"  # "Vice" on light backgrounds
CHARCOAL = "#161b22"  # envelope
