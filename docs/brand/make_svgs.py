# App icon, full detail (128 px and up)

BODY = (100, 100, 824, 824, 185.4)  # Apple icon grid


def body_layers(p):
    x, y, w, h, r = BODY

    def inset(d):
        return squircle(x + d, y + d, w - 2 * d, h - 2 * d, r - d)

    defs = "\n".join([
        grad(f"{p}rim-edge", [(0, "#a5d6ff"), (0.55, "#79c0ff"), (1, "#4493f8")]),
        grad(f"{p}rim", [(0, "#4493f8"), (0.55, "#388bfd"), (1, "#1158c7")]),
        f'<radialGradient id="{p}night" cx="0.5" cy="0.36" r="0.7">'
        f'<stop offset="0" stop-color="#111a26"/><stop offset="1" stop-color="{NIGHT}"/></radialGradient>',
        f'<clipPath id="{p}inner"><path d="{inset(18)}"/></clipPath>',
    ])
    layers = "\n".join([
        f'<path d="{squircle(x, y, w, h, r)}" fill="url(#{p}rim-edge)"/>',
        f'<path d="{inset(6)}" fill="url(#{p}rim)"/>',
        f'<path d="{inset(18)}" fill="url(#{p}night)"/>',
        f'<g clip-path="url(#{p}inner)"><path d="{inset(18)}" fill="none" stroke="#2f81f7" '
        f'stroke-width="26" opacity="0.6" filter="url(#{p}blur10)"/>'
        f'<path d="{inset(18)}" fill="none" stroke="#4493f8" stroke-width="10" opacity="0.7" '
        f'filter="url(#{p}blur6)"/></g>',
    ])
    return defs, layers


def icon_master(platform):
    x, y, w, h, r = BODY
    defs, layers = body_layers("")
    shadow = ""
    if platform == "macos":
        shadow = (f'<path d="{squircle(x, y, w, h, r)}" transform="translate(0 12)" opacity="0.45" '
                  f'filter="url(#blur14)"/>\n')
    content = f"<defs>\n{defs}\n{mark_defs('')}\n{filters('')}\n</defs>\n{shadow}{layers}\n{mark('')}"
    if platform == "macos":
        return svg((0, 0, 1024, 1024), content)
    # Windows: the same artwork, framed so the body fills 88 % of the canvas, like the small sizes
    # (87 to 92 %) and the square icons of Windows 11 itself. 94 % looked too heavy in the taskbar.
    side = w / 0.88
    o = 512 - side / 2
    return svg((o, o, side, side), content, size=(1024, 1024))


