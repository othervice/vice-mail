# Monochrome glyph (tray, notifications, menus): one colour, works as a macOS template image.

def glyph_mono():
    s = 1.4  # the mark scaled to fill the 1024 canvas
    ox, oy = 64 - ENV[0] * s, 177 - V_TOP * s

    def t(x, y):
        return (ox + x * s, oy + y * s)

    ex0, ey0 = t(ENV[0], ENV[1])
    ex1, ey1 = t(ENV[2], ENV[3])
    w = 76  # outline width
    ring = (rrect(ex0, ey0, ex1 - ex0, ey1 - ey0, 104) +
            rrect(ex0 + w, ey0 + w, ex1 - ex0 - 2 * w, ey1 - ey0 - 2 * w, 104 - w))
    v = [t(*q) for q in V_ALL]
    a0, a1 = t(*APEX[0]), t(*APEX[1])
    flap = (f"M{n(ex0 + w * 0.9)} {n(ey1 - w * 0.9)}L{n(a0[0])} {n(a0[1])}"
            f"M{n(ex1 - w * 0.9)} {n(ey1 - w * 0.9)}L{n(a1[0])} {n(a1[1])}")
    body = "\n".join([
        "<defs><mask id=\"cut\" maskUnits=\"userSpaceOnUse\" x=\"0\" y=\"0\" width=\"1024\" height=\"1024\">",
        '<rect width="1024" height="1024" fill="#fff"/>',
        f'<polygon points="{pts(v)}" fill="#000" stroke="#000" stroke-width="112" stroke-linejoin="round"/>',
        "</mask></defs>",
        '<g mask="url(#cut)">',
        f'<path d="{ring}" fill="currentColor" fill-rule="evenodd"/>',
        f'<path d="{flap}" stroke="currentColor" stroke-width="56" stroke-linecap="round"/>',
        "</g>",
        f'<polygon points="{pts(v)}" fill="currentColor"/>',
    ])
