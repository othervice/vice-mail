HEADER = "<!-- Generated by docs/brand/make_svgs.py. Edit that script, then run scripts/icons.sh. -->"


def n(v):
    """Short number for SVG output."""
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s == "-0" else s


def pts(points):
    return " ".join(f"{n(x)},{n(y)}" for x, y in points)


def svg(view, body, size=None):
    w, h = (size or (view[2], view[3]))
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{n(w)}" height="{n(h)}" '
        f'viewBox="{" ".join(n(v) for v in view)}">\n{HEADER}\n{body}\n</svg>\n'
    )


# Apple's continuous ("squircle") corner, as used by macOS app icons. Constants from the
# PaintCode analysis of UIBezierPath(roundedRect:cornerRadius:).
SQ = (1.52866483, 1.08849323, 0.86840701, 0.63149399, 0.07491100, 0.37282401, 0.16905599)


def squircle(x, y, w, h, r):
    a, b, c, d, e, f, g = (k * r for k in SQ)
    X, Y = x + w, y + h
    return (
        f"M{n(x + a)} {n(y)}H{n(X - a)}"
        f"C{n(X - b)} {n(y)} {n(X - c)} {n(y)} {n(X - d)} {n(y + e)}"
        f"C{n(X - f)} {n(y + g)} {n(X - g)} {n(y + f)} {n(X - e)} {n(y + d)}"
        f"C{n(X)} {n(y + c)} {n(X)} {n(y + b)} {n(X)} {n(y + a)}"
        f"V{n(Y - a)}"
        f"C{n(X)} {n(Y - b)} {n(X)} {n(Y - c)} {n(X - e)} {n(Y - d)}"
        f"C{n(X - g)} {n(Y - f)} {n(X - f)} {n(Y - g)} {n(X - d)} {n(Y - e)}"
        f"C{n(X - c)} {n(Y)} {n(X - b)} {n(Y)} {n(X - a)} {n(Y)}"
        f"H{n(x + a)}"
        f"C{n(x + b)} {n(Y)} {n(x + c)} {n(Y)} {n(x + d)} {n(Y - e)}"
        f"C{n(x + f)} {n(Y - g)} {n(x + g)} {n(Y - f)} {n(x + e)} {n(Y - d)}"
        f"C{n(x)} {n(Y - c)} {n(x)} {n(Y - b)} {n(x)} {n(Y - a)}"
        f"V{n(y + a)}"
        f"C{n(x)} {n(y + b)} {n(x)} {n(y + c)} {n(x + e)} {n(y + d)}"
        f"C{n(x + g)} {n(y + f)} {n(x + f)} {n(y + g)} {n(x + d)} {n(y + e)}"
        f"C{n(x + c)} {n(y)} {n(x + b)} {n(y)} {n(x + a)} {n(y)}Z"
    )


def rrect(x, y, w, h, r):
    """Rounded rectangle with circular corners as a path."""
    X, Y = x + w, y + h
    return (
        f"M{n(x + r)} {n(y)}H{n(X - r)}A{n(r)} {n(r)} 0 0 1 {n(X)} {n(y + r)}V{n(Y - r)}"
        f"A{n(r)} {n(r)} 0 0 1 {n(X - r)} {n(Y)}H{n(x + r)}A{n(r)} {n(r)} 0 0 1 {n(x)} {n(Y - r)}"
        f"V{n(y + r)}A{n(r)} {n(r)} 0 0 1 {n(x + r)} {n(y)}Z"
    )


def grad(id_, stops, x1=0, y1=0, x2=0, y2=1, user=None):
    """Linear gradient; `user` = (x1, y1, x2, y2) in user space instead of the bounding box."""
    if user:
        head = (f'<linearGradient id="{id_}" gradientUnits="userSpaceOnUse" x1="{n(user[0])}" '
                f'y1="{n(user[1])}" x2="{n(user[2])}" y2="{n(user[3])}">')
    else:
        head = f'<linearGradient id="{id_}" x1="{n(x1)}" y1="{n(y1)}" x2="{n(x2)}" y2="{n(y2)}">'
    body = "".join(
        f'<stop offset="{n(o)}" stop-color="{c}"' + (f' stop-opacity="{n(a)}"' if a != 1 else "") + "/>"
        for o, c, a in ((s + (1,))[:3] for s in stops)
    )
    return f"{head}{body}</linearGradient>"


