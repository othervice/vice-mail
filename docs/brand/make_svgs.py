def icon_small(cfg):
    N, m, r, rim = cfg["N"], cfg["m"], cfg["r"], cfg["rim"]
    ex0, ey0, ex1, ey1 = cfg["env"]
    u = cfg["u"]
    top, tip, notch, ox0, ox1, ix0, ix1 = cfg["v"]
    B = N - 2 * m
    er = max(u * 1.6, B * 0.06)  # envelope corner radius
    c = u / 2
    outline = (f"M{n(ex0 + c)} {n(ey0 + u * 1.5)}V{n(ey1 - er)}A{n(er - c)} {n(er - c)} 0 0 0 {n(ex0 + er)} {n(ey1 - c)}"
               f"H{n(ex1 - er)}A{n(er - c)} {n(er - c)} 0 0 0 {n(ex1 - c)} {n(ey1 - er)}V{n(ey0 + u * 1.5)}")
    v_left = [(ox0, top), (ix0, top), (N / 2, notch), (N / 2, tip)]
    v_right = [(ix1, top), (ox1, top), (N / 2, tip), (N / 2, notch)]
    v_halo = [(ix0, top), (ox0, top), (N / 2, tip), (ox1, top), (ix1, top)]
    halo = max(1.0, N / 20)
    flap = ""
    if cfg.get("flap"):  # bottom flap edges, from the inner corners towards the V
        ax = (ex0 + 0.3 * (ex1 - ex0), ex1 - 0.3 * (ex1 - ex0))
        ay = ey0 + 0.45 * (ey1 - ey0)
        flap = (f'<path d="M{n(ex0 + u)} {n(ey1 - u)}L{n(ax[0])} {n(ay)}M{n(ex1 - u)} {n(ey1 - u)}L{n(ax[1])} {n(ay)}" '
                f'stroke="#58a6ff" stroke-width="{n(cfg["flap"])}" stroke-linecap="round"/>')
    defs = "\n".join([
        grad("rim", [(0, "#79c0ff"), (0.5, "#4493f8"), (1, "#1f6feb")]),
        grad("v-left", [(0, "#a5d6ff"), (0.45, "#4493f8"), (1, "#1f6feb")], user=(0, top, 0, tip)),
        grad("v-right", [(0, "#b6e3ff"), (0.45, "#58a6ff"), (1, "#2f81f7")], user=(0, top, 0, tip)),
        grad("outline", [(0, "#6cb6ff"), (1, "#2f81f7")], user=(0, ey0, 0, ey1)),
    ])
    body = "\n".join([
        f"<defs>{defs}</defs>",
        f'<path d="{rrect(m, m, B, B, r)}" fill="url(#rim)"/>',
        f'<path d="{rrect(m + rim, m + rim, B - 2 * rim, B - 2 * rim, max(r - rim, 0.5))}" fill="{NIGHT}"/>',
        # envelope: dark panel, a steel top edge, the blue outline
        f'<path d="{rrect(ex0, ey0, ex1 - ex0, ey1 - ey0, er)}" fill="#212830"/>',
        f'<rect x="{n(ex0 + er * 0.6)}" y="{n(ey0)}" width="{n(ex1 - ex0 - er * 1.2)}" height="{n(max(1, u * 0.67))}" fill="#768390"/>',
        f'<path d="{outline}" fill="none" stroke="url(#outline)" stroke-width="{n(u)}" stroke-linecap="round"/>',
        flap,
        # the V, with a dark halo so it separates from the outline it crosses
        f'<polyline points="{pts(v_halo)}" fill="none" stroke="{NIGHT}" stroke-width="{n(halo * 2)}" stroke-linejoin="round"/>',
        f'<polygon points="{pts(v_left)}" fill="url(#v-left)"/>',
        f'<polygon points="{pts(v_right)}" fill="url(#v-right)"/>',
    ])
    return svg((0, 0, N, N), body)


