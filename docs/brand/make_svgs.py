# The mark: envelope with the V, in 1024 units of the macOS icon grid (body 100..924).
# Measured from the human's original and centred; see docs/brand/README.md.

V_TOP, V_TIP, V_NOTCH = 300, 690, 517
V_OUT = (210, 814)  # outer top corners
V_IN = (355, 669)  # inner top corners
ENV = (192, 372, 832, 778)  # envelope outer box
ENV_R_TOP, ENV_R_BOTTOM = 40, 66
U_W = 26  # width of the blue envelope outline
APEX = ((396, 589), (628, 589))  # where the flap edges meet, left and right
FLAP_START = 416  # y where the top flap edge leaves the envelope side
U_START = 452  # y of the outline's round cap centre

V_LEFT = [(V_OUT[0], V_TOP), (V_IN[0], V_TOP), (512, V_NOTCH), (512, V_TIP)]
V_RIGHT = [(V_IN[1], V_TOP), (V_OUT[1], V_TOP), (512, V_TIP), (512, V_NOTCH)]
V_ALL = [(V_OUT[0], V_TOP), (V_IN[0], V_TOP), (512, V_NOTCH), (V_IN[1], V_TOP), (V_OUT[1], V_TOP), (512, V_TIP)]


def mark_defs(p):
    """Gradients of the mark; `p` prefixes the ids so several marks can share a document."""
    x0, y0, x1, y1 = ENV
    return "\n".join([
        grad(f"{p}v-left", [(0, "#a5d6ff"), (0.3, "#79c0ff"), (0.62, "#388bfd"), (1, "#1f6feb")],
             user=(0, V_TOP, 0, V_TIP)),
        grad(f"{p}v-right", [(0, "#b6e3ff"), (0.32, "#6cb6ff"), (0.66, "#4493f8"), (1, "#1a62dc")],
             user=(0, V_TOP, 0, V_TIP)),
        grad(f"{p}fold", [(0, "#cae8ff", 0.95), (1, "#58a6ff", 0.15)], user=(0, V_TOP, 0, V_NOTCH)),
        grad(f"{p}outline", [(0, "#79c0ff"), (0.45, "#4493f8"), (1, "#1f6feb")], user=(0, U_START, 0, y1)),
        grad(f"{p}back", [(0, "#0a0e14"), (1, "#1b2129")], user=(0, y0, 0, y1)),
        grad(f"{p}bottom-flap", [(0, "#2a313c"), (1, "#0f141b")], user=(0, APEX[0][1], 0, y1)),
        grad(f"{p}top-flap", [(0, "#6e7b8c"), (0.2, "#313946"), (0.5, "#20262f"), (0.8, "#313946"),
                              (1, "#6e7b8c")], user=(x0, 0, x1, 0)),
        grad(f"{p}speed", [(0, "#58a6ff"), (1, "#4493f8", 0)], 0, 0, 1, 0),
    ])


def mark(p, detail=True, speed=False):
    """Envelope and V. `detail` adds the blurred glow and shadow (filters `{p}blur*` needed)."""
    x0, y0, x1, y1 = ENV
    rt, rb = ENV_R_TOP, ENV_R_BOTTOM
    i = 2  # the panel stays inside the outline, so no dark seam shows along its outer edge
    back = (f"M{x0 + i} {y0 + rt}A{rt - i} {rt - i} 0 0 1 {x0 + rt} {y0 + i}H{x1 - rt}"
            f"A{rt - i} {rt - i} 0 0 1 {x1 - i} {y0 + rt}V{y1 - rb}A{rb - i} {rb - i} 0 0 1 {x1 - rb} {y1 - i}"
            f"H{x0 + rb}A{rb - i} {rb - i} 0 0 1 {x0 + i} {y1 - rb}Z")
    # Bottom flap: from the inner bottom corners of the outline up to the two apexes.
    ci = U_W + (ENV_R_BOTTOM - U_W) * 0.29  # inner corner point, 45 degrees on the inner arc
    bl, br = (x0 + ci, y1 - ci), (x1 - ci, y1 - ci)
    bottom_flap = pts([bl, APEX[0], APEX[1], br, (x1 - rb, y1 - 8), (x0 + rb, y1 - 8)])  # corners under the outline
    top_flap = (f"M{x0} {FLAP_START}V{y0 + rt}A{rt} {rt} 0 0 1 {x0 + rt} {y0}H{x1 - rt}"
                f"A{rt} {rt} 0 0 1 {x1} {y0 + rt}V{FLAP_START}L{n(APEX[1][0])} {n(APEX[1][1])}"
                f"L{n(APEX[0][0])} {n(APEX[0][1])}Z")
    c = U_W / 2
    outline = (f"M{x0 + c} {U_START}V{y1 - rb}A{rb - c} {rb - c} 0 0 0 {x0 + rb} {y1 - c}"
               f"H{x1 - rb}A{rb - c} {rb - c} 0 0 0 {x1 - c} {y1 - rb}V{U_START}")
    flap_lines = (f"M{n(bl[0])} {n(bl[1])}L{APEX[0][0]} {APEX[0][1]}M{n(br[0])} {n(br[1])}L{APEX[1][0]} {APEX[1][1]}"
                  f"M{x0 + 2} {FLAP_START + 1}L{APEX[0][0]} {APEX[0][1]}M{x1 - 2} {FLAP_START + 1}L{APEX[1][0]} {APEX[1][1]}")
    corner_light = (f"M{x0 + 1.5} {FLAP_START - 6}V{y0 + rt}A{rt - 1.5} {rt - 1.5} 0 0 1 {x0 + rt} {y0 + 1.5}H{x0 + rt + 46}"
                    f"M{x1 - 1.5} {FLAP_START - 6}V{y0 + rt}A{rt - 1.5} {rt - 1.5} 0 0 0 {x1 - rt} {y0 + 1.5}H{x1 - rt - 46}")
    fold = pts([(512, V_NOTCH), (V_IN[1], V_TOP), (V_IN[1] + 34, V_TOP), (520, V_NOTCH + 22)])
    edges = (f"M{V_OUT[0]} {V_TOP}L512 {V_TIP}L{V_OUT[1]} {V_TOP}"
             f"M{V_IN[0]} {V_TOP}L512 {V_NOTCH}L{V_IN[1]} {V_TOP}")
    out = [f'<path d="{back}" fill="url(#{p}back)"/>',
           f'<polygon points="{bottom_flap}" fill="url(#{p}bottom-flap)"/>',
           f'<path d="{outline}" fill="none" stroke="url(#{p}outline)" stroke-width="{U_W}" stroke-linecap="round"/>']
    if detail:
        out.insert(2, f'<path d="{flap_lines}" fill="none" stroke="#4493f8" stroke-width="12" opacity="0.55" filter="url(#{p}blur6)"/>')
        out.insert(0, f'<path d="{outline}" fill="none" stroke="#388bfd" stroke-width="{U_W + 10}" opacity="0.5" filter="url(#{p}blur10)"/>')
    out += [f'<path d="{top_flap}" fill="url(#{p}top-flap)"/>',
            f'<path d="{flap_lines}" fill="none" stroke="#6cb6ff" stroke-width="3.5" stroke-linecap="round"/>',
            f'<path d="{corner_light}" fill="none" stroke="#d1d9e0" stroke-width="3" stroke-linecap="round" opacity="0.75"/>']
    if detail:
        out += [f'<polygon points="{pts(V_ALL)}" transform="translate(0 22)" opacity="0.8" filter="url(#{p}blur18)"/>',
                f'<polygon points="{pts(V_ALL)}" fill="#2f81f7" opacity="0.9" filter="url(#{p}blur9)"/>']
    out += [f'<polygon points="{pts(V_LEFT)}" fill="url(#{p}v-left)"/>',
            f'<polygon points="{pts(V_RIGHT)}" fill="url(#{p}v-right)"/>',
            f'<polygon points="{fold}" fill="url(#{p}fold)"/>',
            f'<path d="{edges}" fill="none" stroke="#b6e3ff" stroke-width="2.5" stroke-linejoin="round" opacity="0.85"/>']
    if speed:
        out.append(speed_lines(p))
    return "\n".join(out)


def speed_lines(p):
    """Three motion lines leaving the right arm of the V (wordmark only)."""
    lines = []
    for y, end in ((316, 1010), (352, 975), (388, 935)):
        start = V_OUT[1] - (V_OUT[1] - 512) / (V_TIP - V_TOP) * (y - V_TOP) + 26
        lines.append(f'<rect x="{n(start)}" y="{y - 9}" width="{n(end - start)}" height="18" rx="9" '
                     f'fill="url(#{p}speed)"/>')
    return "\n".join(lines)


def filters(p):
    return "\n".join(
        f'<filter id="{p}blur{s}" x="-25%" y="-25%" width="150%" height="150%">'
        f'<feGaussianBlur stdDeviation="{s}"/></filter>'
        for s in (6, 9, 10, 14, 18)
    )


